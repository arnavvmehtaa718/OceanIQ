/**
 * OceanIQ — analysis orchestrator.
 *
 * The single entry point the UI and the REST layer call. It wires the trained
 * model to the decision engines and returns one `AnalysisResult`.
 *
 *   scenario -> forecast -> {timing, port, vessel, route, cost, strategies}
 *            -> {savings, risk, recommendation, alerts, report}
 *
 * Every step is deterministic, so the same scenario always yields the same
 * result — which is what makes the saved-report id meaningful.
 */

